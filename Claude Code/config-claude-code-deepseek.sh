# Claude Code 配置连接到 DeepSeek API

# 设置 DeepSeek API 端点（Anthropic 兼容格式）
export ANTHROPIC_BASE_URL="https://api.deepseek.com/v1"

# 设置你的 DeepSeek API Key
export ANTHROPIC_AUTH_TOKEN="your-deepseek-api-key-here"

# 清空原有的 Anthropic API Key（使用 DeepSeek 代替）
export ANTHROPIC_API_KEY=""

